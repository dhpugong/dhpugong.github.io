export function runNetwork(weights, features) {
  const hidden = weights.hidden.map((hiddenWeights) => activate(dot(hiddenWeights, features)));
  return dot(weights.output, [...hidden, 1]);
}

function dot(weights, values) {
  return weights.reduce((sum, weight, index) => sum + weight * values[index], 0);
}

function activate(value) {
  return Math.tanh(value);
}
